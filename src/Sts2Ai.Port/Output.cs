    /// <summary>gen/fns.rs: every function a delegate that is data can be bound to (World.FnEntry), each with its number,
    /// the code that runs it and the delegate bound to a target; and the table by the game's own name of the method
    /// (`<class>::<method>`, the class by its CLR full name), which is how an export says what a delegate is. A virtual
    /// method is in the table under every class that has a body for it: reflection names the body the object runs.</summary>
    private string Fns()
    {
        var sb = new StringBuilder(Emitter.Header);
        sb.Insert(0, "//! The functions a delegate of the game can be, and the table of them by the game's name of the method.\n");
        sb.Append("use std::any::Any;\n\n");
        var concrete = w.Kinds.Keys.Where(k => k.TypeKind == TypeKind.Class && !k.IsAbstract && !k.IsStatic && w.CatOf(k) is Cat.Translated or Cat.Manual).ToList();
        var byName = new List<(string Clr, string Name)>();
        int id = 0;
        foreach (var e in w.Fns.Values.OrderBy(e => e.Name, StringComparer.Ordinal))
        {
            id++;
            int n = e.Types.Count;
            string generic = $"Fn{n}<{string.Join(", ", e.Types.Append(e.Ret))}>";
            string pointer = $"fn(Obj, {string.Concat(e.Types.Select(t => t + ", "))}&mut Combat) -> {e.Ret}";
            string ps = string.Concat(e.Types.Select((t, i) => $"a{i}: {t}, "));
            string clr = e.Clr;
            sb.Append($"/// C#: {clr}\npub fn {e.Name}(t: Obj) -> {generic} {{\n    Fn{n}::of({id}, t, {e.Name}__f)\n}}\n");
            sb.Append($"fn {e.Name}__f(t: Obj, {ps}c: &mut Combat) -> {e.Ret} {{\n    {e.Call}\n}}\n");
            sb.Append($"static {e.Name.ToUpperInvariant()}: {pointer} = {e.Name}__f;\n\n");
            var names = new SortedSet<string>(StringComparer.Ordinal) { clr };
            if (e.VirtualSlot is { } slot)
            {
                foreach (var k in concrete.Where(k => Derives(k, slot.ContainingType)))
                    if (FindImpl(k, slot) is { IsAbstract: false } impl) names.Add($"{World.FullName(impl.ContainingType)}::{impl.Name}");
            }
            foreach (string name in names) byName.Add((name, e.Name));
        }
        sb.Append("/// One function under the game's name of its method: its number, and the function itself as the delegate's type has it.\n");
        sb.Append("pub type Named = (&'static str, u32, &'static (dyn Any + Send + Sync));\n\n");
        sb.Append("/// Sorted by name. A method that is taken as delegates of two types is there once for each.\npub static BY_NAME: &[Named] = &[\n");
        var ids = w.Fns.Values.OrderBy(e => e.Name, StringComparer.Ordinal).Select((e, i) => (e.Name, Id: i + 1)).ToDictionary(x => x.Name, x => x.Id);
        foreach (var (clr, name) in byName.OrderBy(x => x.Clr, StringComparer.Ordinal).ThenBy(x => x.Name, StringComparer.Ordinal))
            sb.Append($"    (\"{clr}\", {ids[name]}, &{name.ToUpperInvariant()}),\n");
        sb.Append("];\n");
        w.Rep.Count($"functions a delegate can be bound to: {id}");
        return sb.ToString();
    }


    // The game's StringHelper.Slugify, as its three patterns.
    private static readonly System.Text.RegularExpressions.Regex CamelCase = new("([A-Za-z0-9]|\\G(?!^))([A-Z])");
    private static readonly System.Text.RegularExpressions.Regex Whitespace = new("\\s+");
    private static readonly System.Text.RegularExpressions.Regex SpecialChar = new("[^A-Z0-9_]");

    private static string Slugify(string text) =>
        SpecialChar.Replace(Whitespace.Replace(CamelCase.Replace(text.Trim(), "$1_$2").ToUpperInvariant(), "_"), "");

    /// <summary>gen/model_table.rs: what the game's ModelDb knows of each model class by reflection. The id of a class
    /// (ModelDb.GetId: its category, the class directly below AbstractModel, and its own name, both slugified); its two
    /// sorting ids, the place of its category and of its entry among those of every model class of the game in the order
    /// of their ids (ModelIdSerializationCache.Init, which counts the classes outside the engine too); the constructor.</summary>
    private string Models()
    {
        var abstractModel = w.AllTypes.First(t => World.FullName(t) == "MegaCrit.Sts2.Core.Models.AbstractModel");
        bool IsModel(INamedTypeSymbol t)
        {
            for (var b = t.BaseType; b != null; b = b.BaseType) if (Eq.Equals(b.OriginalDefinition, abstractModel)) return true;
            return false;
        }
        (string Category, string Entry) Id(INamedTypeSymbol t)
        {
            var category = t;
            while (!Eq.Equals(category.BaseType!.OriginalDefinition, abstractModel)) category = category.BaseType!.OriginalDefinition;
            string c = Slugify(category.Name);
            if (c.EndsWith("_MODEL")) c = c[..^"_MODEL".Length];
            return (c, Slugify(t.Name));
        }
        // Every model class the game registers: the list its source carries (AbstractModelSubtypes).
        var subtypes = w.AllTypes.First(t => World.FullName(t) == "MegaCrit.Sts2.Core.Models.AbstractModelSubtypes");
        var all = new List<INamedTypeSymbol>();
        foreach (var f in subtypes.GetMembers().OfType<IFieldSymbol>())
            foreach (var r in f.DeclaringSyntaxReferences)
            {
                var model = w.Comp.GetSemanticModel(r.SyntaxTree);
                foreach (var to in r.GetSyntax().DescendantNodes().OfType<Microsoft.CodeAnalysis.CSharp.Syntax.TypeOfExpressionSyntax>())
                    if (model.GetTypeInfo(to.Type).Type is INamedTypeSymbol t && IsModel(t)) all.Add(t.OriginalDefinition);
            }
        all = all.Distinct<INamedTypeSymbol>(Eq).ToList();
        if (all.Count == 0) throw new InvalidDataException("AbstractModelSubtypes lists no model class");
        var ids = all.Select(Id).Distinct().OrderBy(x => x.Category, StringComparer.Ordinal).ThenBy(x => x.Entry, StringComparer.Ordinal).ToList();
        var categories = new Dictionary<string, int> { ["NONE"] = 0 };
        var entries = new Dictionary<string, int> { ["NONE"] = 0 };
        foreach (var (c, e) in ids)
        {
            categories.TryAdd(c, categories.Count);
            entries.TryAdd(e, entries.Count);
        }

        var kinds = w.Kinds.Keys.OrderBy(k => w.Unique(k), StringComparer.Ordinal).ToList();
        var sb = new StringBuilder("//! What the game's ModelDb knows of each model class.\n" + Emitter.Header + "\n");
        sb.Append("/// A model class: its id and its sorting ids.\n#[derive(Clone, Copy, Debug)]\npub struct ModelInfo {\n    pub category: &'static str,\n    pub entry: &'static str,\n    pub category_sorting_id: i32,\n    pub entry_sorting_id: i32,\n}\n\n");
        sb.Append("/// The model classes of the engine, by kind.\npub fn model_info(kind: Kind) -> Option<ModelInfo> {\n    let (category, entry, category_sorting_id, entry_sorting_id) = match kind {\n");
        var concrete = new List<INamedTypeSymbol>();
        foreach (var k in kinds)
        {
            if (k.TypeKind != TypeKind.Class || !IsModel(k)) continue;
            var (c, e) = Id(k);
            // A class that is not registered (an abstract one, a mock outside the list) has an id and no place.
            int ci = categories.GetValueOrDefault(c, -1), ei = all.Contains(k, Eq) ? entries[e] : -1;
            sb.Append($"        Kind::{w.Unique(k)} => (\"{c}\", \"{e}\", {ci}, {ei}),\n");
            if (!k.IsAbstract && all.Contains(k, Eq) && w.CatOf(k) == Cat.Translated && k.InstanceConstructors.Any(x => x.Parameters.Length == 0)) concrete.Add(k);
        }
        sb.Append("        _ => return None,\n    };\n    Some(ModelInfo { category, entry, category_sorting_id, entry_sorting_id })\n}\n\n");
        sb.Append($"/// The model classes the engine can make: those of the game's list that are translated.\npub static MODEL_KINDS: [Kind; {concrete.Count}] = [{string.Join(", ", concrete.Select(k => "Kind::" + w.Unique(k)))}];\n\n");
        sb.Append("/// C#: Activator.CreateInstance(type), for a model class.\npub fn new_model(kind: Kind, c: &mut Combat) -> Obj {\n    match kind {\n");
        foreach (var k in concrete)
        {
            var ctor = k.InstanceConstructors.First(x => x.Parameters.Length == 0);
            sb.Append($"        Kind::{w.Unique(k)} => {w.Path(k, ctor)}::{w.FnName(ctor)}(c),\n");
        }
        sb.Append("        _ => panic!(\"{kind:?} is not a model class of the engine\"),\n    }\n}\n");
        return sb.ToString();
    }

    /// <summary>gen/import.rs: the reader of an export (DESIGN.md, "The export"). It knows both what the schema says an
    /// object looks like there and where each field is in the structs.</summary>
    private string Import(string hash)
    {
        var sb = new StringBuilder("//! The reader of an export of the game's combat: every class's own fields, every arena, the roots.\n" + Emitter.Header);
        sb.Append("use crate::rt::import::*;\nuse serde_json::Value;\n\n");
        sb.Append($"/// The game the engine is a copy of.\npub const GAME: &str = \"{w.Cfg.GameVersion}\";\n");
        sb.Append($"/// The hash of the schema the engine was made with: an export made along another schema is refused.\npub const SCHEMA_HASH: &str = \"{hash}\";\n\n");

        string Fill(INamedTypeSymbol t) => "fill_" + World.Snake(w.Unique(t));
        foreach (var t in stateful.Where(HasFields))
        {
            var lines = new StringBuilder();
            int n = 0;
            foreach (var tp in t.TypeParameters)
                if (w.Erased(tp)) { lines.Append($"    d.{World.TargField(tp)} = field(m, \"{World.TargField(tp)}\")?;\n"); n++; }
            foreach (var (_, name, _, isState) in w.Fields(t))
                if (isState) { lines.Append($"    d.{name} = field(m, \"{Json(name)}\")?;\n"); n++; }
            sb.Append($"fn {Fill(t)}(d: &mut {w.DataName(t)}, o: &Object) -> Res<()> {{\n    let m = level(o, \"{w.Unique(t)}\", {n})?;\n{lines}    Ok(())\n}}\n\n");
        }

        var subs = stateful.Where(t => !w.IsOpen(t) && !Eq.Equals(w.Root(t), t)).ToList();
        foreach (var r in roots)
        {
            string data = w.DataName(r), arena = ArenaField(r), ext = w.Unique(r) + "Ext";
            var carriers = subs.Where(t => Eq.Equals(w.Root(t), r) && HasFields(t)).ToList();
            sb.Append($"fn read_{World.Snake(w.Unique(r))}(v: &Value) -> Res<{data}> {{\n    let o = object(v)?;\n    let kind: Kind = field(o, \"class\")?;\n");
            sb.Append($"    if !is_subclass(kind, Kind::{w.Unique(r)}) {{\n        return Err(format!(\"{{kind:?}} is not a {w.Unique(r)}\"));\n    }}\n");
            sb.Append($"    let mut d = {data} {{ kind, {(carriers.Count > 0 ? $"ext: {ext}::of_kind(kind), " : "")}..Default::default() }};\n");
            int levels = 1;
            foreach (var o in OpenChain(r).Where(HasFields)) { sb.Append($"    {Fill(o)}(&mut d.{World.Ident(w.Unique(o))}, o)?;\n"); levels++; }
            if (HasFields(r)) { sb.Append($"    {Fill(r)}(&mut d, o)?;\n"); levels++; }
            if (carriers.Count == 0) sb.Append($"    members(o, {levels})?;\n");
            else
            {
                sb.Append($"    let levels = {levels}\n        + match &mut d.ext {{\n            {ext}::None => 0,\n");
                foreach (var t in carriers)
                {
                    var chain = new List<INamedTypeSymbol>();
                    for (INamedTypeSymbol? x = t; x != null; x = w.BaseClass(x) is { } b ? Carrier(b) : null) chain.Add(x);
                    sb.Append($"            {ext}::{w.Unique(t)}(x) => {{\n");
                    for (int i = 0; i < chain.Count; i++)
                        sb.Append($"                {Fill(chain[i])}({(i == 0 ? "x" : "&mut x" + string.Concat(Enumerable.Repeat(".base", i)))}, o)?;\n");
                    sb.Append($"                {chain.Count}\n            }}\n");
                }
                sb.Append("        };\n    members(o, levels)?;\n");
            }
            sb.Append("    Ok(d)\n}\n\n");
        }

        sb.Append("/// The arenas of an export, by name: an arena's objects in their order.\npub fn read_arenas(m: &Object, a: &mut Arenas) -> Res<()> {\n    for (name, v) in m {\n        match name.as_str() {\n");
        foreach (var r in roots) sb.Append($"            \"{ArenaField(r)}\" => arena(&mut a.{ArenaField(r)}, name, v, read_{World.Snake(w.Unique(r))})?,\n");
        sb.Append("            _ => return Err(format!(\"no arena {name}\")),\n        }\n    }\n    Ok(())\n}\n\n");

        var rootList = StaticRoots();
        sb.Append($"/// The roots of an export, by name.\npub fn read_roots(m: &Object) -> Res<Roots> {{\n    members(m, {rootList.Count})?;\n    Ok(Roots {{\n");
        foreach (var (_, name, _) in rootList) sb.Append($"        {name}: field(m, \"{name}\")?,\n");
        sb.Append("    })\n}\n\n");

        foreach (var s in w.Structs.Keys.OrderBy(s => w.Unique(s), StringComparer.Ordinal))
        {
            var fields = w.Fields(s).Where(f => f.IsState).ToList();
            sb.Append($"impl Rd for {w.Unique(s)} {{\n    fn rd(v: &Value) -> Res<Self> {{\n");
            // A class held as a value can be null in the game: here that is the value with nothing in it.
            if (s.TypeKind == TypeKind.Class) sb.Append("        if v.is_null() {\n            return Ok(Self::default());\n        }\n");
            sb.Append($"        let m = object(v)?;\n        members(m, {fields.Count})?;\n        Ok({w.Unique(s)} {{\n");
            foreach (var f in fields) sb.Append($"            {f.Name}: field(m, \"{Json(f.Name)}\")?,\n");
            sb.Append("            ..Default::default()\n        })\n    }\n}\n\n");
        }
        return sb.ToString();
    }


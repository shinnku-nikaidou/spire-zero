    /// <summary>gen/saved.rs: the [SavedProperty] properties of each class, as the game's ModelIdSerializationCache
    /// finds them by reflection (Type.GetProperties: the class's own of any access, its ancestors' unless private)
    /// and in the order it sorts them, by the attribute's order and then by name. Each with the code that reads it
    /// and the code that writes it; manual/saved_properties.rs walks the table where the game walks the properties.</summary>
    private string Saved()
    {
        var sb = new StringBuilder(Emitter.Header);
        sb.Insert(0, "//! The [SavedProperty] properties of each class, in the game's order, with the code that reads and writes each.\n");
        sb.Append("use crate::manual::saved_properties::{Prop, Saved};\n\n");
        var accessors = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var lists = new SortedDictionary<string, List<string>>(StringComparer.Ordinal);
        foreach (var k in w.Kinds.Keys.Where(k => k.TypeKind == TypeKind.Class && !k.IsAbstract && !k.IsStatic && w.CatOf(k) == Cat.Translated).OrderBy(k => w.Unique(k), StringComparer.Ordinal))
        {
            var found = new Dictionary<string, (IPropertySymbol P, int Condition, int Order)>();
            for (INamedTypeSymbol? t = k; t != null && World.IsSource(t); t = t.BaseType)
                foreach (var p in t.OriginalDefinition.GetMembers().OfType<IPropertySymbol>())
                {
                    if (p.IsStatic || p.IsIndexer || found.ContainsKey(p.Name)) continue;
                    if (!Eq.Equals(t.OriginalDefinition, k) && p.DeclaredAccessibility == Accessibility.Private) continue;
                    var attribute = p.GetAttributes().FirstOrDefault(a => a.AttributeClass?.Name == "SavedPropertyAttribute");
                    if (attribute == null) continue;
                    var given = attribute.ConstructorArguments;
                    found[p.Name] = (p, given.Length > 0 ? System.Convert.ToInt32(given[0].Value) : 0, given.Length > 1 ? System.Convert.ToInt32(given[1].Value) : 0);
                }
            if (found.Count == 0) continue;
            var entries = new List<string>();
            foreach (var (p, condition, _) in found.Values.OrderBy(x => x.Order).ThenBy(x => x.P.Name, StringComparer.Ordinal))
            {
                string stem = $"{World.Snake(p.ContainingType.Name)}__{World.Snake(p.Name)}";
                if (!accessors.ContainsKey(stem)) accessors[stem] = SavedAccessors(p, stem);
                entries.Add($"Prop {{ name: \"{p.Name}\", condition: {condition}, get: get_{stem}, set: set_{stem} }}");
            }
            string list = string.Join(", ", entries);
            if (!lists.TryGetValue(list, out var kinds)) lists[list] = kinds = [];
            kinds.Add("Kind::" + w.Unique(k));
        }
        foreach (var code in accessors.Values) sb.Append(code);
        int n = 0;
        var arms = new StringBuilder();
        foreach (var (list, kinds) in lists)
        {
            sb.Append($"static P{n}: &[Prop] = &[{list}];\n");
            arms.Append($"        {string.Join(" | ", kinds)} => P{n},\n");
            n++;
        }
        sb.Append("\n/// The saved properties of a class, in the order the game reads and writes them.\npub fn props(kind: Kind) -> &'static [Prop] {\n    match kind {\n")
            .Append(arms).Append("        _ => &[],\n    }\n}\n");
        return sb.ToString();
    }

    /// <summary>The two functions of one saved property: its value as a Saved, and a Saved written to it.</summary>
    private string SavedAccessors(IPropertySymbol p, string stem)
    {
        var type = p.ContainingType;
        string where = $"{type.Name}.{p.Name}";
        if (p.GetMethod == null) throw new InvalidDataException($"{where}: a saved property without a getter");
        string get = $"{w.Path(type, p.GetMethod)}::{w.FnName(p.GetMethod)}(me, c)";
        // What FromInternal makes of a value of each type, and FillInternal's way back.
        (string read, string write) = p.Type switch
        {
            { SpecialType: SpecialType.System_Int32 } => ($"Saved::Int({get})", "v.int()"),
            { SpecialType: SpecialType.System_Boolean } => ($"Saved::Bool({get})", "v.bool()"),
            { SpecialType: SpecialType.System_String } => ($"Saved::of_text({get})", "v.str()"),
            INamedTypeSymbol { TypeKind: TypeKind.Enum, EnumUnderlyingType.SpecialType: SpecialType.System_Int32 } e => ($"Saved::Int({get}.0)", $"{w.RType(e)}(v.int())"),
            IArrayTypeSymbol { ElementType.SpecialType: SpecialType.System_Int32 } => ($"Saved::Ints({get})", "v.ints()"),
            INamedTypeSymbol { Name: "ModelId" } => ($"Saved::of_id({get})", "v.id()"),
            INamedTypeSymbol { Name: "SerializableCard" } => ($"Saved::of_card({get})", "v.card()"),
            INamedTypeSymbol { Name: "List", TypeArguments: [INamedTypeSymbol { Name: "SerializableCard" }] } => ($"Saved::Cards({get})", "v.cards()"),
            _ => throw new InvalidDataException($"{where}: a saved property of type {p.Type}, which SavedProperties.FromInternal does not take"),
        };
        string set = p.SetMethod == null
            ? $"panic!(\"{where}: a saved property without a setter\")"
            : $"{w.Path(type, p.SetMethod)}::{w.FnName(p.SetMethod)}(me, {write}, c)";
        return $"fn get_{stem}(me: Obj, c: &mut Combat) -> Saved {{\n    {read}\n}}\n\nfn set_{stem}(me: Obj, v: Saved, c: &mut Combat) {{\n    {set};\n}}\n\n";
    }


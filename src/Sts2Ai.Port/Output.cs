using System.Text;
using System.Text.Json.Nodes;
using Microsoft.CodeAnalysis;

namespace Sts2Ai.Port;

/// <summary>The files of gen/ that are not one class: the state, the kinds, the enums, the dispatchers, the stubs, the schema.</summary>
public sealed class Output(World w, Emitter em)
{
    private static readonly SymbolEqualityComparer Eq = SymbolEqualityComparer.Default;
    /// <summary>Path below gen/ to text.</summary>
    public readonly SortedDictionary<string, string> Files = new(StringComparer.Ordinal);
    private List<INamedTypeSymbol> stateful = [];
    private List<INamedTypeSymbol> roots = [];

    public void Build(List<Emitter.ClassResult> classes)
    {
        var areas = new SortedDictionary<string, SortedSet<string>>(StringComparer.Ordinal);
        foreach (var cr in classes)
        {
            string area = World.Area(cr.Type), module = w.Module(cr.Type);
            Files[$"{area}/{module}.rs"] = cr.Text;
            if (!areas.TryGetValue(area, out var set)) areas[area] = set = new SortedSet<string>(StringComparer.Ordinal);
            set.Add(module);
        }
        foreach (var (area, modules) in areas)
            Files[$"{area}/mod.rs"] = "// Generated by port. Not in git.\n" + string.Concat(modules.Select(m => $"pub mod {m};\n"));
        stateful = w.StatefulClasses();
        roots = stateful.Where(t => !w.IsOpen(t) && Eq.Equals(w.Root(t), t)).ToList();
        Dispatch(classes);
        Stubs();
        Manual();
        // The state may name more structs and enums; the kinds come last because everything before can add one.
        string state;
        int before;
        do { before = w.Structs.Count + w.Enums.Count + w.Kinds.Count; state = State(); } while (before != w.Structs.Count + w.Enums.Count + w.Kinds.Count);
        Files["state.rs"] = state;
        Files["schema.json"] = Schema();
        Files["enums.rs"] = Enums();
        Files["kinds.rs"] = KindsFile();
        Files["mod.rs"] = "// Generated by port from the game's own code (engine/gen.sh). Not in git.\n#![allow(warnings, clippy::all)]\n\n" +
            "pub mod dispatch;\npub mod enums;\npub mod kinds;\npub mod state;\npub mod stubs;\n" + string.Concat(areas.Keys.Select(a => $"pub mod {a};\n"));
    }

    // ---------------------------------------------------------------- dispatch

    private bool Derives(INamedTypeSymbol k, INamedTypeSymbol of)
    {
        if (of.TypeKind == TypeKind.Interface) return k.AllInterfaces.Any(i => Eq.Equals(i.OriginalDefinition, of));
        for (INamedTypeSymbol? x = k; x != null; x = x.BaseType) if (Eq.Equals(x.OriginalDefinition, of)) return true;
        return false;
    }

    private static IMethodSymbol? FindImpl(INamedTypeSymbol k, IMethodSymbol slot)
    {
        if (slot.ContainingType.TypeKind == TypeKind.Interface)
        {
            foreach (var i in k.AllInterfaces)
            {
                if (!Eq.Equals(i.OriginalDefinition, slot.ContainingType)) continue;
                var member = i.GetMembers(slot.Name).OfType<IMethodSymbol>().FirstOrDefault(x => Eq.Equals(x.OriginalDefinition, slot));
                if (member != null) return (k.FindImplementationForInterfaceMember(member) as IMethodSymbol)?.OriginalDefinition;
            }
            return null;
        }
        for (INamedTypeSymbol? x = k; x != null; x = x.BaseType)
            foreach (var cand in x.OriginalDefinition.GetMembers(slot.Name).OfType<IMethodSymbol>())
                if (Eq.Equals(World.Slot(cand), slot)) return cand;
        return null;
    }

    private void Dispatch(List<Emitter.ClassResult> classes)
    {
        var slots = new HashSet<ISymbol>(w.Slots.Keys, Eq);
        foreach (var cr in classes)
            foreach (var m in cr.Virtuals)
            {
                if (m.IsVirtual || m.IsOverride || m.IsAbstract) slots.Add(World.Slot(m));
                foreach (var i in cr.Type.AllInterfaces)
                {
                    if (!World.IsSource(i) || w.IsDroppedNamed(i)) continue;
                    foreach (var im in i.GetMembers().OfType<IMethodSymbol>())
                        if (Eq.Equals(cr.Type.FindImplementationForInterfaceMember(im)?.OriginalDefinition, m)) slots.Add(im.OriginalDefinition);
                }
            }
        var concrete = w.Kinds.Keys.Where(k => k.TypeKind == TypeKind.Class && !k.IsAbstract && !k.IsStatic && w.CatOf(k) is Cat.Translated or Cat.Manual)
            .OrderBy(k => w.Unique(k), StringComparer.Ordinal).ToList();
        var sb = new StringBuilder(Emitter.Header);
        sb.Insert(0, "//! One function per virtual member: the most derived override for the object's kind.\n");
        int count = 0;
        foreach (var group in slots.OfType<IMethodSymbol>().Where(s => World.IsSource(s.ContainingType) && !w.IsDroppedNamed(s.ContainingType) && !s.IsStatic
                     && s.ContainingType.TypeKind is TypeKind.Class or TypeKind.Interface && !w.IsValue(s.ContainingType))
                     .GroupBy(s => s.ContainingType, Eq).OrderBy(g => w.Unique((INamedTypeSymbol)g.Key!), StringComparer.Ordinal))
        {
            var type = (INamedTypeSymbol)group.Key!;
            var below = concrete.Where(k => Derives(k, type)).ToList();
            var body = new StringBuilder();
            foreach (var slot in group.OrderBy(s => w.FnName(s), StringComparer.Ordinal))
            {
                if (w.IsDropMember(slot)) continue;
                var signed = em.SignatureOf(slot);
                if (signed == null) continue;
                var (name, sig) = signed.Value;
                string args = string.Join(", ", sig.Args.Append("c"));
                string fish = sig.Generics.Length == 0 ? "" : "::<" + string.Join(", ", sig.Generics.Trim('<', '>').Split(',').Select(x => x.Split(':')[0].Trim())) + ">";
                string none = sig.Ret == "()" ? "()" : sig.Ret == "R<()>" ? "Ok(())" : $"panic!(\"{type.Name}.{slot.Name}: the override is presentation\")";
                string PathOf(IMethodSymbol impl)
                {
                    if (w.IsDropMember(impl)) return none;
                    var cat = w.CatOfMember(impl);
                    if (cat == Cat.Stub) w.StubRefs.TryAdd(impl, 0);
                    if (cat == Cat.Manual) w.ManualRefs.TryAdd(impl, 0);
                    return $"{w.Path(impl.ContainingType, impl)}::{w.FnName(impl)}{fish}({args})";
                }
                var arms = new SortedDictionary<string, List<string>>(StringComparer.Ordinal);
                foreach (var k in below)
                {
                    var impl = FindImpl(k, slot);
                    if (impl == null || impl.IsAbstract || Eq.Equals(impl, slot)) continue;
                    string path = PathOf(impl);
                    if (!arms.TryGetValue(path, out var list)) arms[path] = list = [];
                    list.Add("Kind::" + w.Unique(k));
                }
                string fallback = slot.IsAbstract || type.TypeKind == TypeKind.Interface
                    ? $"k => panic!(\"{type.Name}.{slot.Name}: no implementation for {{:?}}\", k)"
                    : $"_ => {PathOf(slot)}";
                body.Append($"    /// C#: virtual {type.Name}.{(slot.AssociatedSymbol ?? slot).Name}\n");
                string ps = string.Join(", ", sig.Params.Append("c: &mut Combat"));
                body.Append($"    pub fn {name}{sig.Generics}({ps}){(sig.Ret == "()" ? "" : " -> " + sig.Ret)} {{\n        match g::kinds::kind_of(me, c) {{\n");
                foreach (var (path, kinds) in arms) body.Append($"            {string.Join(" | ", kinds)} => {path},\n");
                body.Append($"            {fallback},\n        }}\n    }}\n\n");
                count++;
            }
            if (body.Length > 0) sb.Append($"pub mod {w.Module(type)} {{\n    use super::*;\n\n{body}}}\n\n");
        }
        w.Rep.Dispatchers = count;
        Files["dispatch.rs"] = sb.ToString();
    }

    // ---------------------------------------------------------------- stubs and the hand-written members

    private void Stubs()
    {
        var sb = new StringBuilder(Emitter.Header);
        sb.Insert(0, "//! Members translated code uses that are neither translated, hand-written nor presentation. This list is what is left.\n");
        int count = 0;
        foreach (var group in w.StubRefs.Keys.GroupBy(s => s.ContainingType.OriginalDefinition, Eq).OrderBy(g => w.Unique((INamedTypeSymbol)g.Key!), StringComparer.Ordinal))
        {
            var type = (INamedTypeSymbol)group.Key!;
            sb.Append($"pub mod {w.Module(type)} {{\n    use super::*;\n\n");
            var seen = new HashSet<string>();
            foreach (var s in group.OrderBy(s => s.Name, StringComparer.Ordinal).ThenBy(s => s.ToDisplayString(), StringComparer.Ordinal))
            {
                void One(string name, Emitter.Sig sig, string what)
                {
                    if (!seen.Add(name)) return;
                    string ps = string.Join(", ", sig.Params.Append("c: &mut Combat"));
                    sb.Append($"    pub fn {name}{sig.Generics}({ps}){(sig.Ret == "()" ? "" : " -> " + sig.Ret)} {{\n        todo!(\"{what}\")\n    }}\n\n");
                    count++;
                }
                switch (s)
                {
                    case IMethodSymbol m:
                        if (em.SignatureOf(m) is { } a) One(a.Name, a.Sig, $"{type.Name}.{(m.AssociatedSymbol ?? m).Name}");
                        if (m.MethodKind == MethodKind.Constructor && em.SignatureOf(m, true) is { } b) One(b.Name, b.Sig, $"{type.Name}.ctor");
                        break;
                    case IFieldSymbol f:
                        try { One(World.Ident(f.Name.TrimStart('_')) + "_static", new Emitter.Sig("", [], [], w.RType(f.Type)), $"static {type.Name}.{f.Name}"); }
                        catch (Exception e) when (e is Dropped or Unsupported) { }
                        break;
                }
            }
            sb.Append("}\n\n");
        }
        w.Rep.Stubs = count;
        Files["stubs.rs"] = sb.ToString();
    }

    private void Manual()
    {
        var sb = new StringBuilder("# The members translated code calls in crate::manual, with the signature each must have.\n# Generated by port. Not in git.\n\n");
        int count = 0;
        foreach (var group in w.ManualRefs.Keys.GroupBy(s => s.ContainingType.OriginalDefinition, Eq).OrderBy(g => w.Unique((INamedTypeSymbol)g.Key!), StringComparer.Ordinal))
        {
            var type = (INamedTypeSymbol)group.Key!;
            sb.Append($"## m::{w.Module(type)}  ({World.FullName(type)})\n");
            var seen = new HashSet<string>();
            foreach (var s in group.OrderBy(s => s.Name, StringComparer.Ordinal).ThenBy(s => s.ToDisplayString(), StringComparer.Ordinal))
            {
                void One(string name, Emitter.Sig sig)
                {
                    if (!seen.Add(name)) return;
                    sb.Append($"pub fn {name}{sig.Generics}({string.Join(", ", sig.Params.Append("c: &mut Combat"))}){(sig.Ret == "()" ? "" : " -> " + sig.Ret)}\n");
                    count++;
                }
                switch (s)
                {
                    case IMethodSymbol m:
                        if (em.SignatureOf(m) is { } a) One(a.Name, a.Sig);
                        if (m.MethodKind == MethodKind.Constructor && em.SignatureOf(m, true) is { } b) One(b.Name, b.Sig);
                        break;
                    case IFieldSymbol f:
                        try { One(World.Ident(f.Name.TrimStart('_')) + "_static", new Emitter.Sig("", [], [], w.RType(f.Type))); }
                        catch (Exception e) when (e is Dropped or Unsupported) { }
                        break;
                }
            }
            sb.Append('\n');
        }
        w.Rep.ManualRefs = count;
        Files["manual.txt"] = sb.ToString();
    }

    // ---------------------------------------------------------------- state

    private string ArenaField(INamedTypeSymbol root) => World.Ident(w.Unique(root));
    private string Tag(INamedTypeSymbol root) => "TAG_" + World.Snake(w.Unique(root)).ToUpperInvariant();

    private bool HasFields(INamedTypeSymbol t) => w.Fields(t).Any() || t.TypeParameters.Any(w.Erased);

    /// <summary>The nearest class at or above t, below its root, that has fields of its own.</summary>
    private INamedTypeSymbol? Carrier(INamedTypeSymbol t)
    {
        var root = w.Root(t);
        for (INamedTypeSymbol? x = t; x != null && !Eq.Equals(x, root); x = w.BaseClass(x))
            if (HasFields(x)) return x;
        return null;
    }

    private string State()
    {
        var sb = new StringBuilder("//! The state of a combat: one arena per class, one struct per class with fields.\n" + Emitter.Header.Replace("use crate::r#gen::state::*;\n", ""));
        sb.Append("use serde::{Deserialize, Serialize};\n\n");
        for (int i = 0; i < roots.Count; i++) sb.Append($"pub const {Tag(roots[i])}: u8 = {i + 1};\n");
        sb.Append("\n/// Every object of a combat.\n#[derive(Clone, Debug, Default, Serialize, Deserialize)]\npub struct Arenas {\n");
        foreach (var r in roots) sb.Append($"    pub {ArenaField(r)}: Arena<{w.DataName(r)}>,\n");
        sb.Append("}\n\n");
        sb.Append("/// The arena names, by tag: the classes that own an arena.\npub static ARENA_NAMES: &[&str] = &[\"\", " + string.Join(", ", roots.Select(r => $"\"{w.Unique(r)}\"")) + "];\n\n");

        var subs = stateful.Where(t => !w.IsOpen(t) && !Eq.Equals(w.Root(t), t)).ToList();
        var opens = stateful.Where(w.IsOpen).ToList();
        string FieldLines(INamedTypeSymbol t)
        {
            var fs = new StringBuilder();
            foreach (var tp in t.TypeParameters)
                if (w.Erased(tp)) fs.Append($"    pub {World.TargField(tp)}: Kind,\n");
            foreach (var (field, name, type, isState) in w.Fields(t))
                fs.Append(isState ? $"    pub {name}: {type},\n" : $"    #[serde(skip)]\n    pub {name}: {type},\n");
            return fs.ToString();
        }
        const string derive = "#[derive(Clone, Debug, Default, Serialize, Deserialize)]\n#[serde(default)]\n";

        foreach (var o in opens)
        {
            string data = w.DataName(o);
            sb.Append($"/// {World.FullName(o)}: its fields are part of every class directly below it.\n{derive}pub struct {data} {{\n{FieldLines(o)}}}\n\n");
            var under = roots.Where(r => OpenChain(r).Any(x => Eq.Equals(x, o))).ToList();
            string field = World.Ident(w.Unique(o));
            sb.Append($"impl {data} {{\n    pub fn of(me: Obj, c: &Combat) -> &{data} {{\n        match me.tag() {{\n");
            foreach (var r in under) sb.Append($"            {Tag(r)} => &c.a.{ArenaField(r)}[me].{field},\n");
            sb.Append($"            _ => panic!(\"not a {w.Unique(o)}: {{:?}}\", me),\n        }}\n    }}\n");
            sb.Append($"    pub fn of_mut(me: Obj, c: &mut Combat) -> &mut {data} {{\n        match me.tag() {{\n");
            foreach (var r in under) sb.Append($"            {Tag(r)} => &mut c.a.{ArenaField(r)}[me].{field},\n");
            sb.Append($"            _ => panic!(\"not a {w.Unique(o)}: {{:?}}\", me),\n        }}\n    }}\n}}\n\n");
        }

        foreach (var r in roots)
        {
            string data = w.DataName(r), arena = ArenaField(r);
            var carriers = subs.Where(t => Eq.Equals(w.Root(t), r) && HasFields(t)).ToList();
            sb.Append($"/// {World.FullName(r)}\n{derive}pub struct {data} {{\n");
            foreach (var o in OpenChain(r)) sb.Append($"    pub {World.Ident(w.Unique(o))}: {w.DataName(o)},\n");
            sb.Append("    pub kind: Kind,\n").Append(FieldLines(r));
            if (carriers.Count > 0) sb.Append($"    pub ext: {w.Unique(r)}Ext,\n");
            sb.Append("}\n\n");
            sb.Append($"impl Stored for {data} {{\n    const TAG: u8 = {Tag(r)};\n    fn canon() -> &'static Arena<Self> {{ &rt::canon().{arena} }}\n}}\n\n");
            sb.Append($"impl {data} {{\n    pub fn of(me: Obj, c: &Combat) -> &{data} {{ &c.a.{arena}[me] }}\n    pub fn of_mut(me: Obj, c: &mut Combat) -> &mut {data} {{ &mut c.a.{arena}[me] }}\n");
            sb.Append($"    pub fn alloc(kind: Kind, c: &mut Combat) -> Obj {{\n        c.a.{arena}.alloc({data} {{ kind, {(carriers.Count > 0 ? $"ext: {w.Unique(r)}Ext::of_kind(kind), " : "")}..Default::default() }})\n    }}\n}}\n\n");
            if (carriers.Count == 0) continue;
            string ext = w.Unique(r) + "Ext";
            sb.Append($"/// The fields of the classes below {w.Unique(r)}.\n#[derive(Clone, Debug, Default, Serialize, Deserialize)]\npub enum {ext} {{\n    #[default]\n    None,\n");
            foreach (var t in carriers) sb.Append($"    {w.Unique(t)}({w.DataName(t)}),\n");
            sb.Append("}\n\n");
            // Which variant an object of each kind starts with: that of its nearest class with fields.
            sb.Append($"impl {ext} {{\n    pub fn of_kind(kind: Kind) -> {ext} {{\n        match kind {{\n");
            foreach (var t in carriers)
            {
                var kinds = w.Kinds.Keys.Where(k => k.TypeKind == TypeKind.Class && Eq.Equals(w.Root(k), r) && Carrier(k) is { } cc && Eq.Equals(cc, t))
                    .Select(k => "Kind::" + w.Unique(k)).Order(StringComparer.Ordinal).ToList();
                if (kinds.Count > 0) sb.Append($"            {string.Join(" | ", kinds)} => {ext}::{w.Unique(t)}(Default::default()),\n");
            }
            sb.Append($"            _ => {ext}::None,\n        }}\n    }}\n}}\n\n");
            foreach (var t in carriers)
            {
                string td = w.DataName(t);
                var parent = w.BaseClass(t) is { } b ? Carrier(b) : null;
                sb.Append($"/// {World.FullName(t)}\n{derive}pub struct {td} {{\n");
                if (parent != null) sb.Append($"    pub base: {w.DataName(parent)},\n");
                sb.Append(FieldLines(t)).Append("}\n\n");
                // Every class at or below t that has its own variant reaches t's fields through its `base` chain.
                var paths = new List<(string Variant, string Path)>();
                foreach (var d in carriers)
                {
                    int depth = 0;
                    INamedTypeSymbol? x = d;
                    while (x != null && !Eq.Equals(x, t)) { x = w.BaseClass(x) is { } bb ? Carrier(bb) : null; depth++; }
                    if (x != null) paths.Add((w.Unique(d), string.Concat(Enumerable.Repeat(".base", depth))));
                }
                sb.Append($"impl {td} {{\n    pub fn of(me: Obj, c: &Combat) -> &{td} {{\n        match &c.a.{arena}[me].ext {{\n");
                foreach (var (variant, path) in paths) sb.Append($"            {ext}::{variant}(d) => {(path.Length == 0 ? "d" : "&d" + path)},\n");
                sb.Append($"            _ => panic!(\"not a {w.Unique(t)}: {{:?}}\", me),\n        }}\n    }}\n");
                sb.Append($"    pub fn of_mut(me: Obj, c: &mut Combat) -> &mut {td} {{\n        match &mut c.a.{arena}[me].ext {{\n");
                foreach (var (variant, path) in paths) sb.Append($"            {ext}::{variant}(d) => {(path.Length == 0 ? "d" : "&mut d" + path)},\n");
                sb.Append($"            _ => panic!(\"not a {w.Unique(t)}: {{:?}}\", me),\n        }}\n    }}\n}}\n\n");
            }
        }

        sb.Append("/// C#'s MemberwiseClone: a new object with the same fields.\npub fn memberwise_clone(me: Obj, c: &mut Combat) -> Obj {\n    match me.tag() {\n");
        foreach (var r in roots) sb.Append($"        {Tag(r)} => {{ let d = c.a.{ArenaField(r)}[me].clone(); c.a.{ArenaField(r)}.alloc(d) }}\n");
        sb.Append("        _ => panic!(\"memberwise_clone of {:?}\", me),\n    }\n}\n\n");
        sb.Append("/// The class of an object.\npub fn kind_of(me: Obj, c: &Combat) -> Kind {\n    match me.tag() {\n");
        foreach (var r in roots) sb.Append($"        {Tag(r)} => c.a.{ArenaField(r)}[me].kind,\n");
        sb.Append("        _ => Kind::None,\n    }\n}\n\n");

        foreach (var s in w.Structs.Keys.OrderBy(s => w.Unique(s), StringComparer.Ordinal))
        {
            bool copy = w.StructIsCopy(s);
            sb.Append($"/// {World.FullName(s)} (a value)\n#[derive(Clone, {(copy ? "Copy, " : "")}Debug, Default, PartialEq, Serialize, Deserialize)]\n#[serde(default)]\npub struct {w.Unique(s)} {{\n{FieldLines(s)}}}\n\n");
            {
                // Its text: its own ToString when it has one.
                var toString = s.GetMembers("ToString").OfType<IMethodSymbol>().FirstOrDefault(m => m.Parameters.Length == 0 && !m.IsImplicitlyDeclared);
                string text = toString != null && w.CatOf(s) == Cat.Translated ? $"{w.Path(s, toString)}::{w.FnName(toString)}(self.clone(), c)" : "Str::from_string(format!(\"{:?}\", self))";
                sb.Append($"impl ToS for {w.Unique(s)} {{\n    fn to_s(&self, c: &mut Combat) -> Str {{ {text} }}\n}}\n\n");
            }
            // A class held as a value can be null in C#: here that is the value with nothing in it.
            if (s.TypeKind == TypeKind.Class) sb.Append($"impl IsNull for {w.Unique(s)} {{\n    fn is_null(&self) -> bool {{ *self == Self::default() }}\n}}\n\n");
            if (s.AllInterfaces.Any(i => i.Name == "IComparable" && i.TypeArguments.Length == 1 && Eq.Equals(i.TypeArguments[0].OriginalDefinition, s)))
            {
                var compare = s.GetMembers("CompareTo").OfType<IMethodSymbol>().FirstOrDefault(m => m.Parameters.Length == 1 && Eq.Equals(m.Parameters[0].Type.OriginalDefinition, s));
                if (compare != null && w.CatOf(s) != Cat.Stub)
                    sb.Append($"impl Cmp for {w.Unique(s)} {{\n    fn cmp_net(&self, other: &Self, c: &mut Combat) -> i32 {{ {w.Path(s, compare)}::{w.FnName(compare)}(self.clone(), other.clone(), c) }}\n}}\n\n");
            }
        }
        return sb.ToString();
    }

    /// <summary>The open classes above a root, outermost first.</summary>
    private List<INamedTypeSymbol> OpenChain(INamedTypeSymbol root)
    {
        var list = new List<INamedTypeSymbol>();
        for (var b = w.BaseClass(root); b != null; b = w.BaseClass(b)) list.Insert(0, b);
        return list;
    }

    // ---------------------------------------------------------------- kinds and enums

    private string KindsFile()
    {
        var kinds = w.Kinds.Keys.OrderBy(k => w.Unique(k), StringComparer.Ordinal).ToList();
        var sb = new StringBuilder("//! The classes of the game the engine knows, as values.\nuse crate::rt::*;\nuse serde::{Deserialize, Serialize};\n\n");
        sb.Append("#[derive(Copy, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Debug, Default, Serialize, Deserialize)]\n#[repr(u16)]\npub enum Kind {\n    #[default]\n    None,\n");
        foreach (var k in kinds) sb.Append($"    {w.Unique(k)},\n");
        sb.Append("}\n\n");
        sb.Append($"/// The C# name of each class (typeof(T).Name).\npub static KIND_NAMES: [&str; {kinds.Count + 1}] = [\"\", {string.Join(", ", kinds.Select(k => $"\"{k.Name}\""))}];\n\n");
        sb.Append($"pub static ALL_KINDS: [Kind; {kinds.Count + 1}] = [Kind::None, {string.Join(", ", kinds.Select(k => "Kind::" + w.Unique(k)))}];\n\n");
        sb.Append($"/// The classes and interfaces above each class.\nstatic ANCESTORS: [&[Kind]; {kinds.Count + 1}] = [\n    &[],\n");
        foreach (var k in kinds)
        {
            var up = new List<string>();
            for (var b = k.BaseType; b != null; b = b.BaseType)
                if (w.Kinds.ContainsKey(b.OriginalDefinition)) up.Add("Kind::" + w.Unique(b));
            foreach (var i in k.AllInterfaces)
                if (w.Kinds.ContainsKey(i.OriginalDefinition)) up.Add("Kind::" + w.Unique(i));
            sb.Append($"    &[{string.Join(", ", up.Distinct())}],\n");
        }
        sb.Append("];\n\n");
        sb.Append("pub fn kind_name(k: Kind) -> Str {\n    Str::lit(KIND_NAMES[k as usize])\n}\n\n");
        sb.Append("/// Whether a class is, or derives from, or implements another.\npub fn is_subclass(k: Kind, of: Kind) -> bool {\n    k == of || ANCESTORS[k as usize].contains(&of)\n}\n\n");
        sb.Append("pub use crate::r#gen::state::kind_of;\n\n");
        foreach (var k in kinds) sb.Append($"pub type {w.Unique(k)} = Obj;\n");
        return sb.ToString();
    }

    private string Enums()
    {
        var sb = new StringBuilder("//! The game's enums: a number with named values, as in C#.\nuse crate::rt::*;\nuse serde::{Deserialize, Serialize};\n\n");
        foreach (var e in w.Enums.Keys.OrderBy(e => w.Unique(e), StringComparer.Ordinal))
        {
            string name = w.Unique(e), under = w.RType(e.EnumUnderlyingType);
            sb.Append($"/// {World.FullName(e)}\n#[derive(Copy, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Debug, Default, Serialize, Deserialize)]\n#[serde(transparent)]\npub struct {name}(pub {under});\n");
            sb.Append($"#[allow(non_upper_case_globals)]\nimpl {name} {{\n");
            var members = e.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue).ToList();
            foreach (var f in members) sb.Append($"    pub const {World.EnumMember(f.Name)}: {name} = {name}({System.Convert.ToString(f.ConstantValue, System.Globalization.CultureInfo.InvariantCulture)});\n");
            sb.Append($"    pub fn name(self) -> Option<&'static str> {{\n        match self.0 {{\n");
            var seen = new HashSet<string>();
            foreach (var f in members)
            {
                string v = System.Convert.ToString(f.ConstantValue, System.Globalization.CultureInfo.InvariantCulture)!;
                if (seen.Add(v)) sb.Append($"            {v} => Some(\"{f.Name}\"),\n");
            }
            sb.Append("            _ => None,\n        }\n    }\n}\n");
            sb.Append($"cs_enum!({name}, {under});\n\n");
        }
        return sb.ToString();
    }


    private JsonNode TypeDesc(ITypeSymbol t)
    {
        if (t is ITypeParameterSymbol) return new JsonObject { ["kind"] = "ref", ["class"] = "Object" };
        if (t is IArrayTypeSymbol arr) return new JsonObject { ["kind"] = "list", ["of"] = TypeDesc(arr.ElementType) };
        var n = (INamedTypeSymbol)t;
        if (World.IsNullable(n, out var inner)) return new JsonObject { ["kind"] = "nullable", ["of"] = TypeDesc(inner) };
        switch (n.SpecialType)
        {
            case SpecialType.System_Boolean: return new JsonObject { ["kind"] = "bool" };
            case SpecialType.System_Decimal: return new JsonObject { ["kind"] = "decimal" };
            case SpecialType.System_String: return new JsonObject { ["kind"] = "string" };
            case SpecialType.System_Char: return new JsonObject { ["kind"] = "char" };
            case SpecialType.System_Single or SpecialType.System_Double: return new JsonObject { ["kind"] = "float", ["rust"] = w.RType(n) };
            case SpecialType.System_Object: return new JsonObject { ["kind"] = "ref", ["class"] = "Object" };
            case not SpecialType.None: return new JsonObject { ["kind"] = "int", ["rust"] = w.RType(n) };
        }
        if (n.IsTupleType) return new JsonObject { ["kind"] = "tuple", ["items"] = new JsonArray(n.TupleElements.Select(e => TypeDesc(e.Type)).ToArray()) };
        switch (World.CollOf(n))
        {
            case World.Coll.Vec or World.Coll.Ordered: return new JsonObject { ["kind"] = "list", ["of"] = TypeDesc(n.TypeArguments[0]) };
            case World.Coll.Set: return new JsonObject { ["kind"] = "set", ["of"] = TypeDesc(n.TypeArguments[0]) };
            case World.Coll.Queue: return new JsonObject { ["kind"] = "queue", ["of"] = TypeDesc(n.TypeArguments[0]) };
            case World.Coll.Stack: return new JsonObject { ["kind"] = "stack", ["of"] = TypeDesc(n.TypeArguments[0]) };
            case World.Coll.Dict: return new JsonObject { ["kind"] = "dict", ["key"] = TypeDesc(n.TypeArguments[0]), ["value"] = TypeDesc(n.TypeArguments[1]) };
        }
        string meta = World.MetaName(n);
        if (meta == "System.Collections.Generic.KeyValuePair`2") return new JsonObject { ["kind"] = "pair", ["key"] = TypeDesc(n.TypeArguments[0]), ["value"] = TypeDesc(n.TypeArguments[1]) };
        if (meta == "System.Type") return new JsonObject { ["kind"] = "kind" };
        if (n.TypeKind == TypeKind.Enum) return new JsonObject { ["kind"] = "enum", ["name"] = w.Unique(n), ["rust"] = w.RType(n.EnumUnderlyingType) };
        if (w.IsValue(n)) return new JsonObject { ["kind"] = "struct", ["name"] = w.Unique(n) };
        return new JsonObject { ["kind"] = "ref", ["class"] = w.Unique(n) };
    }

    private JsonArray FieldsDesc(INamedTypeSymbol t)
    {
        var arr = new JsonArray();
        foreach (var (field, name, type, isState) in w.Fields(t))
        {
            if (!isState) continue;
            arr.Add(new JsonObject { ["name"] = name, ["cs"] = field.Name, ["type"] = TypeDesc(field.Type) });
        }
        return arr;
    }

    private string Schema()
    {
        var classes = new JsonArray();
        foreach (var t in stateful.OrderBy(t => w.Unique(t), StringComparer.Ordinal))
        {
            var root = w.Root(t);
            classes.Add(new JsonObject
            {
                ["name"] = w.Unique(t),
                ["cs"] = World.FullName(t),
                ["base"] = w.BaseClass(t) is { } b ? w.Unique(b) : null,
                ["arena"] = w.IsOpen(t) ? null : ArenaField(root),
                ["open"] = w.IsOpen(t),
                ["abstract"] = t.IsAbstract,
                ["type_parameters"] = new JsonArray(t.TypeParameters.Where(w.Erased).Select(p => (JsonNode)World.TargField(p)).ToArray()),
                ["fields"] = FieldsDesc(t),
            });
        }
        var structs = new JsonArray();
        foreach (var s in w.Structs.Keys.OrderBy(s => w.Unique(s), StringComparer.Ordinal))
            structs.Add(new JsonObject { ["name"] = w.Unique(s), ["cs"] = World.FullName(s), ["fields"] = FieldsDesc(s) });
        var enums = new JsonArray();
        foreach (var e in w.Enums.Keys.OrderBy(e => w.Unique(e), StringComparer.Ordinal))
        {
            var members = new JsonObject();
            foreach (var f in e.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue))
                members[f.Name] = JsonValue.Create(System.Convert.ToInt64(f.ConstantValue));
            enums.Add(new JsonObject { ["name"] = w.Unique(e), ["cs"] = World.FullName(e), ["rust"] = w.RType(e.EnumUnderlyingType), ["members"] = members });
        }
        var doc = new JsonObject
        {
            ["format"] = 1,
            ["arenas"] = new JsonArray(roots.Select(r => (JsonNode)ArenaField(r)).ToArray()),
            ["classes"] = classes,
            ["structs"] = structs,
            ["enums"] = enums,
        };
        return doc.ToJsonString(new System.Text.Json.JsonSerializerOptions { WriteIndented = true }) + "\n";
    }

using System.Collections.Concurrent;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;

namespace Sts2Ai.Port;

/// <summary>Writes the Rust module of one translated class: one function per member.</summary>
public sealed class Emitter(World w)
{
    private static readonly SymbolEqualityComparer Eq = SymbolEqualityComparer.Default;
    private readonly ConcurrentDictionary<SyntaxTree, SemanticModel> models = new();
    /// <summary>Functions whose translation rustc refused, as module::function: their bodies become todo!.</summary>
    public HashSet<string> Quarantine = [];

    public sealed class ClassResult
    {
        public required INamedTypeSymbol Type;
        public string Text = "";
        /// <summary>Methods that could be presentation as a whole: nothing written, something left out.</summary>
        public List<IMethodSymbol> Hollow = [];
        /// <summary>Every method and accessor of the class that fills a virtual slot, or is one.</summary>
        public List<IMethodSymbol> Virtuals = [];
        public int Translated, Failed, Presentation, Quarantined, LeftOut;
    }

    public const string Header = "// Generated by port from the game's own code (engine/gen.sh). Not in git.\n" +
        "use crate::r#gen as g;\nuse crate::manual as m;\nuse crate::rt;\nuse crate::rt::*;\nuse crate::r#gen::enums::*;\nuse crate::r#gen::kinds::*;\nuse crate::r#gen::state::*;\n\n";

    private SemanticModel Model(SyntaxTree tree) => models.GetOrAdd(tree, t => w.Comp.GetSemanticModel(t));

    // ---------------------------------------------------------------- signatures

    public sealed record Sig(string Generics, List<string> Params, List<string> Args, string Ret);

    public static string CtorName(string newName) => "ctor" + newName[3..];

    /// <summary>The Rust signature of a method or accessor. Throws Dropped when a type in it is presentation.</summary>
    public Sig Signature(IMethodSymbol m, Body body, bool ctorBody = false)
    {
        var ps = new List<string>();
        var args = new List<string>();
        var generics = new List<string>();
        var type = m.ContainingType;
        if (m.IsStatic || m.MethodKind == MethodKind.Constructor)
            foreach (var tp in type.TypeParameters)
            {
                if (w.Erased(tp)) { ps.Add($"k_{World.Snake(tp.Name)}: Kind"); args.Add($"k_{World.Snake(tp.Name)}"); }
                else generics.Add($"{tp.Name}: Val");
            }
        foreach (var tp in m.TypeParameters)
        {
            if (w.Erased(tp)) { ps.Add($"k_{World.Snake(tp.Name)}: Kind"); args.Add($"k_{World.Snake(tp.Name)}"); }
            else generics.Add($"{tp.Name}: Val" + (tp.ConstraintTypes.Any(c => c.Name == "IComparable") ? " + Cmp" : ""));
        }
        bool isStruct = w.IsValue(type);
        if (!m.IsStatic && (m.MethodKind != MethodKind.Constructor || ctorBody))
        {
            ps.Add(isStruct ? $"mut me: {w.RType(type)}" : $"me: {w.RType(type)}");
            args.Add("me");
        }
        var rets = new List<string>();
        if (!m.ReturnsVoid && m.MethodKind != MethodKind.Constructor)
        {
            if (w.IsDropped(m.ReturnType)) throw new Dropped(m.ReturnType.Name);
            rets.Add(w.RType(m.ReturnType));
        }
        foreach (var p in m.Parameters)
        {
            // A parameter of a presentation type is not there in Rust.
            if (w.IsDropped(p.Type)) continue;
            string t = w.RType(p.Type);
            if (p.RefKind is RefKind.Out or RefKind.Ref) rets.Add(t);
            if (p.RefKind == RefKind.Out) continue;
            ps.Add($"mut {body.ParamName(p)}: {t}");
            args.Add(body.ParamName(p));
        }
        if (m.IsAsync && m.ReturnsVoid) throw new Unsupported("async void");
        string ret = rets.Count == 0 ? "()" : rets.Count == 1 ? rets[0] : "(" + string.Join(", ", rets) + ")";
        if (m.MethodKind == MethodKind.Constructor && !ctorBody) ret = w.RType(type);
        return new Sig(generics.Count == 0 ? "" : "<" + string.Join(", ", generics) + ">", ps, args, ret);
    }

    public static string Fn(string doc, string name, Sig sig, string body)
    {
        string ps = string.Join(", ", sig.Params.Append("c: &mut Combat"));
        string ret = sig.Ret == "()" ? "" : $" -> {sig.Ret}";
        return $"/// {doc}\npub fn {name}{sig.Generics}({ps}){ret} {{\n{body}}}\n\n";
    }

    /// <summary>The signature of a member for a stub, a dispatcher or the list of hand-written members; null when it cannot be written.</summary>
    public (string Name, Sig Sig)? SignatureOf(IMethodSymbol m, bool ctorBody = false)
    {
        try
        {
            var body = new Body(w, m.ContainingType, m);
            string name = w.FnName(m);
            return (ctorBody ? CtorName(name) : name, Signature(m, body, ctorBody));
        }
        catch (Exception e) when (e is Dropped or Unsupported) { return null; }
    }

    // ---------------------------------------------------------------- one class

    private IOperation? BodyOp(IMethodSymbol m, out bool hasBody)
    {
        hasBody = false;
        var syntax = m.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax();
        if (syntax == null) return null;
        var model = Model(syntax.SyntaxTree);
        switch (syntax)
        {
            case ArrowExpressionClauseSyntax arrow:
                hasBody = true;
                // The clause, not its expression: the conversion to the return type is on the implied return.
                return model.GetOperation(arrow) ?? model.GetOperation(arrow.Expression);
            case AccessorDeclarationSyntax acc:
                if (acc.Body == null && acc.ExpressionBody == null) return null;
                hasBody = true;
                return model.GetOperation(acc);
            case BaseMethodDeclarationSyntax md:
                if (md.Body == null && md.ExpressionBody == null) return null;
                hasBody = true;
                return model.GetOperation(md);
            default:
                return null;
        }
    }

    private bool PresentationSignature(IMethodSymbol m) => w.IsDropped(m.ReturnType);

    /// <summary>Whether a method implements a member of a library interface (IConvertible, IEnumerable, ..): nothing in the engine calls those.</summary>
    private static bool ImplementsLibraryInterface(IMethodSymbol m)
    {
        if (m.ExplicitInterfaceImplementations.Any(i => !World.IsSource(i.ContainingType))) return true;
        foreach (var i in m.ContainingType.AllInterfaces)
        {
            if (World.IsSource(i)) continue;
            foreach (var im in i.GetMembers().OfType<IMethodSymbol>())
                if (Eq.Equals(m.ContainingType.FindImplementationForInterfaceMember(im), m)) return true;
        }
        return false;
    }

    public ClassResult Class(INamedTypeSymbol t)
    {
        var r = new ClassResult { Type = t };
        var sb = new StringBuilder(Header);
        sb.Insert(0, $"//! {World.FullName(t)}\n");
        string module = $"{World.Area(t)}::{w.Module(t)}";

        void Method(IMethodSymbol m, string? autoField = null)
        {
            if (w.IsManualMember(m) || w.Cfg.DropMembers.Contains(t.Name + "." + (m.AssociatedSymbol ?? m).Name) || w.Cfg.DropMembers.Contains(t.Name + ".*")) return;
            if (PresentationSignature(m)) { r.Presentation++; return; }
            if (m.IsVirtual || m.IsOverride || m.IsAbstract || m.ExplicitInterfaceImplementations.Length > 0 || ImplementsInterface(m)) r.Virtuals.Add(m);
            if (w.AutoDropped.Contains(m)) { r.Presentation++; return; }
            if (m.IsAbstract || m.IsExtern) return;
            string name = w.FnName(m);
            string doc = $"C#: {t.Name}.{(m.AssociatedSymbol ?? m).Name}{(m.MethodKind == MethodKind.PropertySet ? " (set)" : "")}";
            var body = new Body(w, t, m.AssociatedSymbol ?? m);
            Sig sig;
            try { sig = Signature(m, body); }
            catch (Dropped) { r.Presentation++; return; }
            catch (Unsupported e)
            {
                // No signature: the function cannot even be declared. Callers fail on the same type and become todo! themselves.
                if (ImplementsLibraryInterface(m)) { r.Presentation++; return; }
                w.Rep.Failed($"{t.Name}.{m.Name}", "signature: " + e.Message);
                r.Failed++;
                return;
            }
            string text;
            if (Quarantine.Contains($"{module}::{name}"))
            {
                text = $"todo!(\"port: rustc refused the translation of {t.Name}.{m.Name}\")\n";
                r.Quarantined++;
            }
            else if (autoField == "")
            {
                text = $"todo!(\"port: the field of {t.Name}.{(m.AssociatedSymbol ?? m).Name} is not kept\")\n";
                r.Failed++;
            }
            else if (autoField != null)
            {
                text = m.MethodKind == MethodKind.PropertyGet ? $"{w.DataName(t)}::of(me, c).{autoField}.clone()\n" : $"{w.DataName(t)}::of_mut(me, c).{autoField} = value;\n";
                r.Translated++;
            }
            else
            {
                var op = BodyOp(m, out bool hasBody);
                try
                {
                    if (!hasBody) throw new Unsupported("no body in the decompiled source");
                    if (op == null) throw new Unsupported("code the compiler could not bind");
                    text = body.Method(m, op);
                    r.Translated++;
                    r.LeftOut += body.LeftOut;
                    if (body.Written == 0 && body.LeftOut > 0 && m.MethodKind == MethodKind.Ordinary && (m.ReturnsVoid || (World.IsTask(m.ReturnType, out var res) && res == null))
                        && m.Parameters.All(p => p.RefKind == RefKind.None))
                        r.Hollow.Add(m);
                }
                catch (Unsupported e) when (e.Message.StartsWith("returns presentation") && op is not Microsoft.CodeAnalysis.Operations.IMethodBodyOperation { BlockBody.Operations.Length: > 1 })
                {
                    // All the member does is hand out presentation (an asset path, a text): the next pass treats it as such.
                    // Until then it is still a function, because a dispatcher may name it.
                    r.Hollow.Add(m);
                    r.Presentation++;
                    text = $"todo!(\"port: {t.Name}.{m.Name} is presentation\")\n";
                }
                catch (Exception e) when (e is Unsupported or Dropped)
                {
                    w.Rep.Failed($"{t.Name}.{m.Name}", e is Dropped ? $"presentation where a value is needed ({e.Message})" : e.Message);
                    text = $"todo!(\"port: {t.Name}.{m.Name}: {Body.Escape(e.Message)}\")\n";
                    r.Failed++;
                }
            }
            sb.Append(Fn(doc, name, sig, text));
        }

        bool isStruct = w.IsValue(t);
        foreach (var member in t.GetMembers())
        {
            switch (member)
            {
                case IMethodSymbol { MethodKind: MethodKind.Ordinary or MethodKind.ExplicitInterfaceImplementation or MethodKind.UserDefinedOperator or MethodKind.Conversion } m when !m.IsImplicitlyDeclared:
                    Method(m);
                    break;
                case IMethodSymbol { MethodKind: MethodKind.Constructor } ctor when !t.IsStatic:
                    if (ctor.IsImplicitlyDeclared && (isStruct || t.InstanceConstructors.Length > 1)) break;
                    Constructor(t, ctor, sb, r, module);
                    break;
                case IPropertySymbol p:
                {
                    if (w.IsDropped(p.Type)) { r.Presentation++; break; }
                    var auto = t.GetMembers().OfType<IFieldSymbol>().FirstOrDefault(f => Eq.Equals(f.AssociatedSymbol, p));
                    if (auto != null && isStruct) break;
                    if (auto != null && p.IsStatic) { StaticValue(t, auto, p.Type, World.Ident(p.Name), sb, r); break; }
                    string? autoField = auto == null ? null : w.StateField(auto);
                    if (auto != null && autoField == null) w.Rep.Failed($"{t.Name}.{p.Name}", "field is not kept");
                    // An auto-property whose field is not kept still has its accessors (a todo!), so that what names them compiles.
                    string? accessor = auto == null ? null : autoField ?? "";
                    if (p.GetMethod != null) Method(p.GetMethod, accessor);
                    if (p.SetMethod != null) Method(p.SetMethod, accessor);
                    break;
                }
                case IFieldSymbol { IsStatic: true, IsConst: false, AssociatedSymbol: null } f:
                    if (w.IsDropped(f.Type)) break;
                    StaticValue(t, f, f.Type, World.Ident(f.Name.TrimStart('_')) + "_static", sb, r);
                    break;
            }
        }
        r.Text = sb.ToString();
        return r;
    }

    private static bool ImplementsInterface(IMethodSymbol m)
    {
        foreach (var i in m.ContainingType.AllInterfaces)
            foreach (var im in i.GetMembers().OfType<IMethodSymbol>())
                if (Eq.Equals(m.ContainingType.FindImplementationForInterfaceMember(im), m)) return true;
        return false;
    }

    /// <summary>A static field or static auto-property: a function that gives its initial value. Right only while nothing writes it.</summary>
    private void StaticValue(INamedTypeSymbol t, IFieldSymbol f, ITypeSymbol type, string name, StringBuilder sb, ClassResult r)
    {
        if (w.IsManualMember(f.AssociatedSymbol ?? f)) return;
        string rtype;
        try { rtype = w.RType(type); }
        catch (Exception e) when (e is Dropped or Unsupported) { return; }
        string text;
        var body = new Body(w, t, f);
        if (w.StaticState(f.AssociatedSymbol ?? f) is { } inCombat)
        {
            // A static that is state: part of the combat.
            sb.Append(Fn($"C#: static {t.Name}.{(f.AssociatedSymbol ?? f).Name} (state)", name, new Sig("", [], [], rtype), $"c.s.{inCombat}.clone()\n"));
            r.Translated++;
            return;
        }
        try
        {
            if (w.IsObj(type)) throw new Unsupported("a static object");
            var init = Initializer(f.AssociatedSymbol ?? f) ?? throw new Unsupported("a static without an initializer");
            text = body.Initial(init) + "\n";
            r.Translated++;
        }
        catch (Exception e) when (e is Unsupported or Dropped)
        {
            w.Rep.Failed($"{t.Name}.{f.Name}", e.Message);
            text = $"todo!(\"port: static {t.Name}.{(f.AssociatedSymbol ?? f).Name}: {Body.Escape(e.Message)}\")\n";
            r.Failed++;
        }
        sb.Append(Fn($"C#: static {t.Name}.{(f.AssociatedSymbol ?? f).Name}", name, new Sig("", [], [], rtype), text));
    }

    private IOperation? Initializer(ISymbol fieldOrProperty)
    {
        var syntax = fieldOrProperty.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax();
        EqualsValueClauseSyntax? init = syntax switch
        {
            VariableDeclaratorSyntax v => v.Initializer,
            PropertyDeclarationSyntax p => p.Initializer,
            _ => null,
        };
        if (init == null) return null;
        var op = Model(init.SyntaxTree).GetOperation(init);
        return op switch { IFieldInitializerOperation fi => fi.Value, IPropertyInitializerOperation pi => pi.Value, _ => op };
    }

    private void Constructor(INamedTypeSymbol t, IMethodSymbol ctor, StringBuilder sb, ClassResult r, string module)
    {
        if (w.IsManualMember(ctor)) return;
        if (PresentationSignature(ctor)) { r.Presentation++; return; }
        bool isStruct = w.IsValue(t);
        string name = w.FnName(ctor);
        var body = new Body(w, t, ctor);
        Sig sig, inner;
        try
        {
            sig = Signature(ctor, body);
            inner = Signature(ctor, body, ctorBody: true);
        }
        catch (Exception e) when (e is Dropped or Unsupported)
        {
            if (e is Unsupported) { w.Rep.Failed($"{t.Name}.ctor", "signature: " + e.Message); r.Failed++; }
            else r.Presentation++;
            return;
        }
        string text;
        if (Quarantine.Contains($"{module}::{CtorName(name)}") || Quarantine.Contains($"{module}::{name}"))
        {
            text = $"todo!(\"port: rustc refused the translation of {t.Name}.ctor\")\n";
            r.Quarantined++;
        }
        else
        {
            try
            {
                var op = BodyOp(ctor, out bool hasBody);
                if (hasBody && op == null) throw new Unsupported("code the compiler could not bind");
                var head = new StringBuilder();
                bool chainsToThis = op is IConstructorBodyOperation { Initializer: { } init0 } && Unwrap(init0) is IInvocationOperation { TargetMethod: var target } && Eq.Equals(target.ContainingType.OriginalDefinition, t);
                if (!isStruct)
                    foreach (var tp in t.TypeParameters)
                        if (w.Erased(tp)) head.Append($"{w.DataName(t)}::of_mut(me, c).{World.TargField(tp)} = k_{World.Snake(tp.Name)};\n");
                if (!chainsToThis)
                {
                    foreach (var f in t.GetMembers().OfType<IFieldSymbol>())
                    {
                        if (f.IsStatic || f.IsConst || w.IsDropped(f.Type)) continue;
                        var init = Initializer(f.AssociatedSymbol ?? f);
                        if (init == null) continue;
                        string? field = isStruct ? World.FieldName(f) : w.StateField(f);
                        if (field == null) continue;
                        string place = isStruct ? $"me.{field}" : $"{w.DataName(t)}::of_mut(me, c).{field}";
                        try { head.Append($"{{ let __v = {body.Initial(init)}; {place} = __v; }}\n"); }
                        catch (Dropped) { }
                        catch (Unsupported e)
                        {
                            w.Rep.Failed($"{t.Name}.{f.Name} (initializer)", e.Message);
                            head.Append($"panic!(\"port: initializer of {t.Name}.{f.Name}: {Body.Escape(e.Message)}\");\n");
                        }
                    }
                    // A constructor that names no base constructor runs the base's parameterless one.
                    if (!isStruct && op is not IConstructorBodyOperation { Initializer: not null } && w.BaseClass(t) is { } b)
                        head.Append(body.BaseCtor(t, b)).Append('\n');
                }
                text = body.Method(ctor, op, head.ToString());
                r.Translated++;
                r.LeftOut += body.LeftOut;
            }
            catch (Exception e) when (e is Unsupported or Dropped)
            {
                w.Rep.Failed($"{t.Name}.ctor", e.Message);
                text = $"todo!(\"port: {t.Name}.ctor: {Body.Escape(e.Message)}\");\n";
                r.Failed++;
            }
        }
        if (isStruct)
        {
            sb.Append(Fn($"C#: new {t.Name}", name, sig, $"let mut me = <{w.RType(t)} as Default>::default();\n{text}me\n"));
            return;
        }
        sb.Append(Fn($"C#: the body of {t.Name}'s constructor", CtorName(name), inner, text));
        if (t.IsAbstract) return;
        string args = string.Join(", ", inner.Args.Append("c"));
        sb.Append(Fn($"C#: new {t.Name}", name, sig, $"let me = {w.DataName(w.Root(t))}::alloc({w.KindOf(t)}, c);\n{CtorName(name)}({args});\nme\n"));
    }

    private static IOperation Unwrap(IOperation op) => op is IExpressionStatementOperation es ? es.Operation : op;
}
